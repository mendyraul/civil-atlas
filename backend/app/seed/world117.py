def source(
    id: str,
    title: str,
    citation: str,
    confidence: str,
    review_status: str,
    notes: str,
    link: str | None = None,
) -> EvidenceRecord:
    return EvidenceRecord(
        id=id,
        title=title,
        citation=citation,
        confidence=confidence,
        review_status=review_status,
        notes=notes,
        link=link,
    )


